package com.gdtahara.gdtaharabackend.model;

import jakarta.persistence.*;
import lombok.Data;
import java.math.BigDecimal;
import java.time.LocalDate;
import java.time.LocalDateTime;

@Data
@Entity
@Table(name = "tank_meter_reading")
public class TankMeterReading {

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    private String tankId;
    private String readingType; // SHIFT_START, SHIFT_END, ADHOC
    private BigDecimal meterValueKg;
    private String shiftCode;
    private LocalDate shiftDate;
    private String recordedBy;
    private LocalDateTime recordedAt;
    private String note;
    private Boolean autoGenerated = false;
    // FK to another TankMeterReading used as seed for auto-generated start reading
    private Long sourceReadingId;

    @PrePersist
    protected void onCreate() {
        if (this.recordedAt == null) this.recordedAt = LocalDateTime.now();
    }
}
