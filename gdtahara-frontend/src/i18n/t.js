// Merge extra labels into base translations
for (const lang of Object.keys(extra)) {
  Object.assign(translations[lang], extra[lang]);
}

export const getLang = () => {
  try {
    const stored = localStorage.getItem('lang');
    if (stored === 'th' || stored === 'en') return stored;
  } catch {}
  const nav = (navigator.language || 'th').toLowerCase();
  return nav.startsWith('th') ? 'th' : 'en';
};

export const setLang = (lang) => {
  try { localStorage.setItem('lang', lang); } catch {}
  try { document.documentElement.lang = lang; } catch {}
};

export const t = (key) => {
  const lang = getLang();
  const value = translations[lang]?.[key] ?? translations.th[key] ?? key;
  return value;
};

// Initialize document lang on load
setLang(getLang());
